
"""
Semifori Elec Tech - Municipal Maintenance Portal.

Displays maintenance tickets generated by SmartLight AI.
Allows municipal staff to track and update repair statuses.
"""

import json
from datetime import datetime
from pathlib import Path

import pandas as pd
import streamlit as st

import config as cfg
from ticketing import verify_ticket


# ---------------------------------------------------------------
# Portal settings
# ---------------------------------------------------------------

STATUS_OPTIONS = [
    "Pending",
    "In Progress",
    "Resolved",
]

STATUS_FILE = cfg.MUNICIPAL_DIR / "ticket_status.json"


# ---------------------------------------------------------------
# Create required folders
# ---------------------------------------------------------------

def ensure_portal_folders():
    """Create the municipal portal storage folders."""

    cfg.MUNICIPAL_DIR.mkdir(parents=True, exist_ok=True)
    cfg.MUNICIPAL_TICKETS_DIR.mkdir(parents=True, exist_ok=True)


# ---------------------------------------------------------------
# Load ticket status information
# ---------------------------------------------------------------

def load_statuses():
    """Load maintenance statuses saved by municipal staff."""

    ensure_portal_folders()

    if not STATUS_FILE.exists():
        return {}

    try:
        return json.loads(STATUS_FILE.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}


# ---------------------------------------------------------------
# Save ticket status information
# ---------------------------------------------------------------

def save_statuses(statuses):
    """Save updated maintenance statuses."""

    ensure_portal_folders()

    STATUS_FILE.write_text(
        json.dumps(statuses, indent=4),
        encoding="utf-8"
    )


# ---------------------------------------------------------------
# Load dispatched maintenance tickets
# ---------------------------------------------------------------

def load_municipal_tickets():
    """
    Read ticket files from the existing maintenance outbox
    and the municipal tickets folder.

    Original ticket files are not modified when statuses change.
    """

    ensure_portal_folders()

    directories = [
        cfg.PORTAL_DIR,
        cfg.MUNICIPAL_TICKETS_DIR,
    ]

    tickets_by_id = {}

    for directory in directories:

        if not directory.exists():
            continue

        for file_path in directory.glob("*.json"):

            try:
                ticket = json.loads(
                    file_path.read_text(encoding="utf-8")
                )

                ticket_id = ticket.get("ticket_id")

                if ticket_id:
                    tickets_by_id[ticket_id] = ticket

            except (json.JSONDecodeError, OSError):
                continue

    return list(tickets_by_id.values())


# ---------------------------------------------------------------
# Update a maintenance ticket
# ---------------------------------------------------------------

def update_ticket_status(ticket_id, new_status):
    """Update a ticket without altering its original signature."""

    if new_status not in STATUS_OPTIONS:
        raise ValueError("Invalid maintenance status.")

    statuses = load_statuses()

    statuses[ticket_id] = {
        "status": new_status,
        "updated_at": datetime.now().isoformat(timespec="seconds"),
    }

    save_statuses(statuses)


# ---------------------------------------------------------------
# Prepare municipal ticket information
# ---------------------------------------------------------------

def prepare_ticket_data(tickets):
    """Combine ticket information with saved maintenance statuses."""

    statuses = load_statuses()
    rows = []

    for ticket in tickets:

        ticket_id = ticket.get("ticket_id", "Unknown")

        saved_status = statuses.get(ticket_id, {})

        status = saved_status.get(
            "status",
            "Pending"
        )

        rows.append({
            "Ticket ID": ticket_id,
            "Streetlight ID": ticket.get("asset_id", "Unknown"),
            "Fault Type": ticket.get("fault_type", "Unknown"),
            "Priority": ticket.get("priority", "Unknown"),
            "Confidence": ticket.get("confidence", 0),
            "Status": status,
            "Reported At": ticket.get("created_at", "Unknown"),
            "Signature Valid": verify_ticket(ticket),
        })

    return pd.DataFrame(rows)


# ---------------------------------------------------------------
# Municipal dashboard
# ---------------------------------------------------------------

def render_municipal_portal():
    """Display the municipal maintenance dashboard in Streamlit."""

    ensure_portal_folders()

    st.title("🏛️ Municipal Maintenance Portal")

    st.caption(
        f"{cfg.MUNICIPALITY_NAME} | "
        "Streetlight Fault Management Centre"
    )

    st.divider()

    tickets = load_municipal_tickets()

    if not tickets:

        st.info(
            "No maintenance tickets have been received yet. "
            "Run AI monitoring and dispatch tickets from the "
            "SmartLight AI Tickets tab."
        )

        return

    ticket_data = prepare_ticket_data(tickets)

    # -----------------------------------------------------------
    # Dashboard metrics
    # -----------------------------------------------------------

    total = len(ticket_data)

    pending = int(
        (ticket_data["Status"] == "Pending").sum()
    )

    in_progress = int(
        (ticket_data["Status"] == "In Progress").sum()
    )

    resolved = int(
        (ticket_data["Status"] == "Resolved").sum()
    )

    high_priority = int(
        (ticket_data["Priority"] == "High").sum()
    )

    st.subheader("Maintenance Overview")

    c1, c2, c3, c4, c5 = st.columns(5)

    c1.metric("Reported Faults", total)
    c2.metric("Pending", pending)
    c3.metric("In Progress", in_progress)
    c4.metric("Resolved", resolved)
    c5.metric("High Priority", high_priority)

    st.divider()

    # -----------------------------------------------------------
    # Ticket overview
    # -----------------------------------------------------------

    st.subheader("Reported Streetlight Faults")

    filter_status = st.selectbox(
        "Filter by maintenance status",
        ["All", "Pending", "In Progress", "Resolved"]
    )

    if filter_status == "All":
        displayed = ticket_data
    else:
        displayed = ticket_data[
            ticket_data["Status"] == filter_status
        ]

    st.dataframe(
        displayed,
        use_container_width=True,
        hide_index=True,
    )

    st.divider()

    # -----------------------------------------------------------
    # Individual ticket management
    # -----------------------------------------------------------

    st.subheader("Manage Maintenance Tickets")

    statuses = load_statuses()

    for ticket in tickets:

        ticket_id = ticket.get("ticket_id", "Unknown")

        saved_status = statuses.get(ticket_id, {})

        current_status = saved_status.get(
            "status",
            "Pending"
        )

        with st.expander(
            f"{ticket.get('asset_id', 'Unknown')} | "
            f"{ticket.get('fault_type', 'Unknown')} | "
            f"{ticket_id}"
        ):

            left, right = st.columns(2)

            with left:

                st.write(
                    f"**Fault:** {ticket.get('fault_type', 'Unknown')}"
                )

                st.write(
                    f"**Priority:** {ticket.get('priority', 'Unknown')}"
                )

                st.write(
                    f"**Confidence:** "
                    f"{ticket.get('confidence', 0):.1%}"
                )

                st.write(
                    f"**Reported:** {ticket.get('created_at', 'Unknown')}"
                )

            with right:

                st.write(
                    f"**Current status:** {current_status}"
                )

                signature_valid = verify_ticket(ticket)

                if signature_valid:
                    st.success("Ticket signature verified.")
                else:
                    st.error(
                        "Ticket signature invalid. "
                        "Check whether the ticket was altered."
                    )

            st.write("**Diagnostic summary**")

            st.write(ticket.get("summary", "No summary available."))

            diagnostics = ticket.get("diagnostics", {})

            if diagnostics:

                st.write("**Sensor readings**")

                st.json(diagnostics)

            st.write("**Recommended maintenance action**")

            st.write(
                ticket.get(
                    "recommended_action",
                    "No recommendation available."
                )
            )

            new_status = st.selectbox(
                "Update maintenance status",
                STATUS_OPTIONS,
                index=STATUS_OPTIONS.index(current_status)
                if current_status in STATUS_OPTIONS else 0,
                key=f"status_{ticket_id}",
            )

            if st.button(
                "Save Maintenance Status",
                key=f"save_{ticket_id}",
            ):

                update_ticket_status(ticket_id, new_status)

                st.success(
                    f"Ticket {ticket_id} updated to {new_status}."
                )

                st.rerun()

    st.divider()

    # -----------------------------------------------------------
    # Maintenance summary
    # -----------------------------------------------------------

    st.subheader("Maintenance Progress")

    progress = resolved / total if total else 0

    st.progress(progress)

    st.caption(
        f"{resolved} of {total} reported faults have been marked "
        f"as resolved ({progress:.0%})."
    )

    st.caption(
        "Semifori Elec Tech | Municipal Maintenance Portal"
    )
